const mockTitles = {
  pending: 'Тестове замовлення створено',
  approved: 'Тестове оформлення успішне',
  declined: 'Тестову оплату відхилено',
  canceled: 'Тестову оплату скасовано',
  refunded: 'Тестове повернення',
  enrolled: 'Тестовий запис',
};
export function orderStatusLabel(order?: Status) {
  if (!order) return ['Перевіряємо замовлення', 'Зачекайте кілька секунд.'];
  if (order.mode === 'mock') {
    return [
      mockTitles[order.status],
      'Це демонстрація: кошти не списувалися, квиток чи доступ не надавалися, підтвердження на email не надсилалося.',
    ];
  }
  if (order.learningAccess) {
    return [
      'Ваш курс уже в кабінеті',
      order.mode === 'disabled'
        ? 'Доступ надано без оплати. Увійдіть за email, який ви вказали під час оформлення, і починайте навчання'
        : 'Оплату підтверджено. Увійдіть за email, який ви вказали під час оформлення, і починайте навчання',
    ];
  }
  if (order.productKind === 'product' && order.status === 'approved') {
    return [
      'Оплату підтверджено',
      'Дякуємо! Підтвердження надіслано на ваш email, команда академії зв’яжеться з вами щодо деталей.',
    ];
  }
  return labels[order.status];
}
